const lower = new Map<string, GlossaryKey>();
for (const k of Object.keys(GLOSSARY) as GlossaryKey[]) lower.set(k.toLocaleLowerCase('uk'), k);
for (const [a, k] of Object.entries(ALIASES)) lower.set(a.toLocaleLowerCase('uk'), k);

/** Знаходить статтю за ключем або синонімом (без урахування регістру) */
export function lookup(key: string): GlossaryEntry | null {
	if (key in GLOSSARY) return GLOSSARY[key as GlossaryKey];
	const k = lower.get(key.trim().toLocaleLowerCase('uk'));
	return k ? GLOSSARY[k] : null;
}

/** Усі статті в алфавітному порядку — для довідки чи списку термінів */
export function allTerms(): { key: GlossaryKey; entry: GlossaryEntry }[] {
	return (Object.keys(GLOSSARY) as GlossaryKey[])
		.map((key) => ({ key, entry: GLOSSARY[key] as GlossaryEntry }))
		.sort((a, b) => a.entry.term.localeCompare(b.entry.term, 'uk'));
}
