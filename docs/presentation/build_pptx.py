def main() -> None:
    files = sorted((HERE / "slides").glob("s*.png"))
    assert len(files) == len(NOTES), f"{len(files)} слайдів, {len(NOTES)} нотаток"
    prs = Presentation()
    prs.slide_width, prs.slide_height = Emu(12192000), Emu(6858000)  # 16:9
    blank = prs.slide_layouts[6]
    for f, note in zip(files, NOTES):
        s = prs.slides.add_slide(blank)
        s.shapes.add_picture(str(f), 0, 0, prs.slide_width, prs.slide_height)
        s.notes_slide.notes_text_frame.text = note
    out = HERE / "Insight-Tool-pitch.pptx"
    prs.save(out)
    print(out, len(files), "слайдів")


if __name__ == "__main__":
    main()
